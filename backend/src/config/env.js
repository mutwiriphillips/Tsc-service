require('dotenv').config({ quiet: true });
const { z } = require('zod');

const schema = z.object({
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  PORT: z.coerce.number().default(4000),
  DATABASE_URL: z.string().min(1),
  JWT_OFFICER_SECRET: z.string().min(32),
  JWT_TEACHER_SECRET: z.string().min(32),
  OFFICER_TOKEN_TTL: z.string().default('8h'),
  TEACHER_TOKEN_TTL: z.string().default('2h'),
  // Either 64 hex characters (a raw 32-byte key) or any random string of 32+
  // characters, from which a 32-byte key is derived (lib/crypto.js). The second
  // form accepts secrets generated by hosting platforms such as Render.
  DATA_ENCRYPTION_KEY: z.string().min(32, 'must be at least 32 characters'),
  NATIONAL_ID_PEPPER: z.string().min(16),
  MFA_REQUIRED: z
    .string()
    .default('true')
    .transform((v) => v === 'true'),
  // Comma-separated web origins. A bare host name (as Render provides) is treated as https://<host>.
  CORS_ORIGIN: z
    .string()
    .default('http://localhost:3000')
    .transform((v) =>
      v
        .split(',')
        .map((o) => o.trim())
        .filter(Boolean)
        .map((o) => (/^https?:\/\//.test(o) ? o : `https://${o}`).replace(/\/$/, '')),
    ),
});

const parsed = schema.safeParse(process.env);
if (!parsed.success) {
  console.error('Invalid environment configuration:');
  for (const issue of parsed.error.issues) console.error(`  ${issue.path.join('.')}: ${issue.message}`);
  process.exit(1);
}
const env = parsed.data;

// Refuse to run in production on development secrets or without officer MFA.
if (env.NODE_ENV === 'production') {
  const looksDev = (v) => /^(dev-|ci-)|change-me/i.test(v);
  const problems = [];
  if (looksDev(env.JWT_OFFICER_SECRET)) problems.push('JWT_OFFICER_SECRET is a development value');
  if (looksDev(env.JWT_TEACHER_SECRET)) problems.push('JWT_TEACHER_SECRET is a development value');
  if (env.JWT_OFFICER_SECRET === env.JWT_TEACHER_SECRET) problems.push('officer and teacher JWT secrets must differ');
  if (/^0+$/.test(env.DATA_ENCRYPTION_KEY) || looksDev(env.DATA_ENCRYPTION_KEY)) problems.push('DATA_ENCRYPTION_KEY is a development value');
  if (looksDev(env.NATIONAL_ID_PEPPER)) problems.push('NATIONAL_ID_PEPPER is a development value');
  if (!env.MFA_REQUIRED) problems.push('MFA_REQUIRED must be true in production');
  if (problems.length) {
    console.error('Refusing to start in production:\n  ' + problems.join('\n  '));
    process.exit(1);
  }
}

module.exports = env;
